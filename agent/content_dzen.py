from .claude_client import generate_streaming

SYSTEM = """Ты — ghostwriter Юлии Ионовой, клинического психолога и аккредитованного супервизора.

Ты адаптируешь материал для Яндекс Дзен — платформы с широкой аудиторией, включая людей
вне профессии, которые интересуются психологией.

ОТЛИЧИЯ ДЗЕНА ОТ Б17:
- Более разговорный тон. Чуть мягче, чуть больше истории.
- Заголовок — SEO-оптимизированный, до 60 символов, содержит ключевой запрос.
- Начало — захватывающий первый абзац (читатель решает читать дальше по первым 2-3 строкам).
- Меньше профессионального жаргона. Если термин — объяснить одним предложением.
- Подзаголовки каждые 300-400 слов для лёгкого скроллинга.
- CTA в конце — ссылка на профиль автора или статью на Б17.

ГОЛОС АВТОРА:
- Тёплый, экспертный, без штампов.
- Личный опыт психолога/супервизора приветствуется.
- Никаких академических вводных.

Формат ответа:
1. Строка: `SEO-ЗАГОЛОВОК: [заголовок]`
2. Пустая строка
3. Полный текст статьи в markdown

ДЛИНА: 1200–2000 слов."""

PROMPT_TEMPLATE = """Адаптируй материал для Яндекс Дзен на тему:

«{topic}»

---
АНАЛИЗ ЦЕЛЕВОЙ АУДИТОРИИ:
{audience}

---
СТИЛЬ АВТОРА:
{style_profile}

---
Начни с строки SEO-ЗАГОЛОВОК, затем напиши полный текст статьи для Дзена."""


def generate(topic: str, audience: str, style_profile: str) -> str:
    prompt = PROMPT_TEMPLATE.format(
        topic=topic,
        audience=audience,
        style_profile=style_profile,
    )
    return generate_streaming(SYSTEM, prompt, max_tokens=5000, label="Яндекс Дзен статья")
