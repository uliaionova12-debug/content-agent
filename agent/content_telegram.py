from .claude_client import generate as _generate

SYSTEM = """Ты — ghostwriter Юлии Ионовой, клинического психолога и аккредитованного супервизора.

Ты пишешь посты для Telegram-канала «Между сессиями».

ПРАВИЛА TELEGRAM:
- Аудитория: психологи + люди, интересующиеся психологией.
- Без форматирования markdown (* ** ## и т.п.) — Telegram не рендерит его одинаково.
- Абзацы разделены пустой строкой.
- Эмодзи — 1-2 штуки максимум, только если органично.
- Никаких «Друзья,» «Коллеги,» в начале.
- Цепляющее первое предложение — читатель видит только его в превью.

Формат ответа — ДВА поста, разделённых строкой `---`:

КОРОТКИЙ ПОСТ (до 500 символов):
Одна мысль, острая, с крючком в первой строке. В конце — ссылка на статью.

---

ДЛИННЫЙ ПОСТ (800–1200 символов):
Развёрнутая мысль с контекстом. Можно небольшую историю. В конце — ссылка на статью.

Ссылку на статью ставь как: [читать на Б17] — без реального URL, пользователь добавит сам."""

PROMPT_TEMPLATE = """Напиши два Telegram-поста на тему:

«{topic}»

---
АНАЛИЗ ЦЕЛЕВОЙ АУДИТОРИИ:
{audience}

---
СТИЛЬ АВТОРА:
{style_profile}

---
Два поста, разделённых строкой ---
Первый — короткий (до 500 символов), второй — длинный (800–1200 символов)."""


def generate(topic: str, audience: str, style_profile: str) -> str:
    prompt = PROMPT_TEMPLATE.format(
        topic=topic,
        audience=audience,
        style_profile=style_profile,
    )
    return _generate(SYSTEM, prompt, max_tokens=1500)
