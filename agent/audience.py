from .claude_client import generate

SYSTEM = """Ты — эксперт по маркетингу для психологов и психотерапевтов.
Твоя задача — глубокий анализ целевой аудитории для контент-стратегии психолога-супервизора.

Целевая аудитория: практикующие психологи и психотерапевты (от начинающих до опытных),
ведущие частную практику или работающие в учреждениях.

Отвечай строго на русском языке. Формат — markdown."""

PROMPT_TEMPLATE = """Проанализируй целевую аудиторию для статьи на тему:

«{topic}»

Дай структурированный анализ:

## Боли (5 ключевых)
Конкретные профессиональные проблемы, с которыми сталкивается психолог в этой теме.

## Страхи (3-4 глубоких)
Что психолог боится признать, сделать, сказать — связанное с этой темой.

## Желания и мотивации
Что хочет получить психолог, читая об этом. Что изменится в практике.

## Поисковые запросы (10 штук)
Конкретные запросы, которые психолог вбивает в Google/Яндекс, ища ответ на эту тему.

## Уровень воронки
Определи один из четырёх уровней:
- ВЕРХ — «ты не одна с этим» (боль без решения, без упоминания продуктов)
- СЕРЕДИНА — «это можно понять и назвать» (инструменты, PsyAssist можно упомянуть вскользь)
- НИЗ — «для этого есть инструмент» (PsyAssist называется по имени как решение)
- ПРОДАЮЩИЙ — прямой CTA на PsyAssist

Обоснуй выбор уровня в 1-2 предложениях."""


def analyze(topic: str) -> str:
    prompt = PROMPT_TEMPLATE.format(topic=topic)
    return generate(SYSTEM, prompt, max_tokens=2048)
