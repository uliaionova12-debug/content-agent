from .claude_client import generate as _generate

SYSTEM = """Ты — ghostwriter Юлии Ионовой, клинического психолога и аккредитованного супервизора.

Ты пишешь посты для сообщества ВКонтакте, аудитория — практикующие психологи.

ПРАВИЛА ВК:
- Живой, но профессиональный тон.
- Первые 2-3 строки — самое важное (остальное скрыто под «читать далее»).
- Длина: 400–600 символов.
- Хештеги в конце — 5-7 штук: общие (#психология, #психолог) + тематические.
- Без markdown-форматирования — только чистый текст.
- Можно вопрос в конце для вовлечения аудитории (необязательно).

В конце — строка с хештегами отдельно."""

PROMPT_TEMPLATE = """Напиши пост для ВКонтакте на тему:

«{topic}»

---
АНАЛИЗ ЦЕЛЕВОЙ АУДИТОРИИ:
{audience}

---
СТИЛЬ АВТОРА:
{style_profile}

---
Пост 400–600 символов, в конце отдельной строкой хештеги."""


def generate(topic: str, audience: str, style_profile: str) -> str:
    prompt = PROMPT_TEMPLATE.format(
        topic=topic,
        audience=audience,
        style_profile=style_profile,
    )
    return _generate(SYSTEM, prompt, max_tokens=800)
